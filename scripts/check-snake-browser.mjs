import assert from 'node:assert/strict'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
// Put the first food directly in front of the initial snake, without touching game internals.
await page.addInitScript(() => { Math.random = () => 208.5 / 397 })
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
  await page.goto(process.env.PORTFOLIO_URL || 'http://127.0.0.1:4174/')
  const entry = page.getByRole('link', { name: 'Play Little Sunshine Snake', exact: true })
  await entry.waitFor({ timeout: 5000 })
  assert.equal(await page.locator('iframe').count(), 0, 'game does not load on homepage')
  await entry.click()
  const game = page.frameLocator('iframe[title="Little Sunshine Snake"]')
  await game.locator('#game').waitFor()
  await game.locator('#game').click()
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('Space')
  assert.match(await game.locator('#status-text').textContent(), /Paused/)
  await page.screenshot({ path: join(tmpdir(), 'portfolio-snake-desktop.png') })
  await game.locator('#restart').click()
  await game.locator('#game').click()
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(170)
  await page.keyboard.press('Space')
  assert.equal(await game.locator('#score').textContent(), '1')
  await page.reload()
  await game.locator('#game').waitFor()
  assert.equal(await game.locator('#best-score').textContent(), '1', 'best score survives reload')
  await game.locator('#game').click()
  await page.keyboard.press('ArrowRight')
  await game.locator('#game-over').waitFor({ state: 'visible', timeout: 5000 })
  await game.locator('#retry-overlay').click()
  assert.equal(await game.locator('#score').textContent(), '0')
  await page.setViewportSize({ width: 390, height: 844 })
  await game.getByRole('button', { name: 'Move up', exact: true }).click()
  await game.locator('#pause-toggle').click()
  assert.match(await game.locator('#status-text').textContent(), /Paused/)
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  assert(await game.locator('body').evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: join(tmpdir(), 'portfolio-snake-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).click()
  await page.getByRole('button', { name: '切换到中文', exact: true }).click()
  assert.match(await page.locator('h1').textContent(), /追一束光/)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 320, height: 680 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.getByRole('button', { name: 'Switch to English', exact: true }).click()
  await page.getByRole('link', { name: 'Back to portfolio', exact: true }).click()
  assert.equal(await page.locator('iframe').count(), 0, 'game unloads on exit')
  assert.equal(errors.length, 0, errors.join('\n'))
  console.log('PASS: lazy entry, keyboard start/pause, scoring/persistence, wall collision/retry, touch controls, mobile overflow, language/theme and route cleanup')
} finally { await browser.close() }
